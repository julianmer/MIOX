from __future__ import annotations

import json

import pytest

# own
from miox import Format, sniff
from tests.conftest import GOLDEN

DATA_SUFFIXES = {
    ".dat",
    ".rda",
    ".spar",
    ".sdat",
    ".list",
    ".data",
    ".7",
    ".dcm",
    ".ima",
    ".nii",
    ".gz",
    ".raw",
    ".mrui",
    ".h5",
}


def _records():
    path = GOLDEN / "sniff.json"
    if not path.is_file():
        return []
    return sorted(json.loads(path.read_text()).items())


@pytest.mark.data
@pytest.mark.parametrize(
    "relpath,expected", _records(), ids=lambda x: x if isinstance(x, str) else ""
)
def test_sniff_golden(public_data, relpath, expected):
    path = public_data / relpath
    if not path.exists():
        pytest.skip("file not fetched")
    s = sniff(path)
    got = {"format": s.format, "vendor": s.vendor, "kind": s.kind}
    assert got == expected


@pytest.mark.data
def test_private_data_files_are_recognised(private_roots):
    """Private sets: no data file may come back unknown. Paths are never recorded."""
    unknown = []
    for root in private_roots:
        for p in root.rglob("*"):
            if p.name.startswith("Adj") or "LaTeX_Extras" in p.parts:
                continue  # Bruker adjustment results, LaTeX build products
            if p.is_file() and p.suffix.lower() in DATA_SUFFIXES:
                if sniff(p).format == Format.UNKNOWN:
                    unknown.append(p.name)
    assert unknown == []
