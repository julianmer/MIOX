from __future__ import annotations

import pytest

# own
from tests.records.records import ReadRecords


@pytest.fixture(scope="module")
def records() -> ReadRecords:
    return ReadRecords()


@pytest.mark.data
@pytest.mark.parametrize(
    "relpath,expected",
    sorted(ReadRecords().expected().items()),
    ids=lambda x: x if isinstance(x, str) else "",
)
def test_read_record(public_data, records, relpath, expected):
    path = public_data / relpath
    if not path.exists() or records.is_lfs_pointer(path):
        pytest.skip("file not fetched")
    assert records.differences(expected, records.record(path)) == []
