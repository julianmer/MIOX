from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# own
from miox.audit import audit  # noqa: E402
from miox.sniff import NIFTI_MRS, sniff  # noqa: E402
from tests.conftest import PUBLIC_DATA  # noqa: E402

DOCS = Path(__file__).resolve().parents[1] / "docs" / "coverage"


def main() -> int:
    DOCS.mkdir(parents=True, exist_ok=True)
    sections = []
    for path in sorted(q for top in PUBLIC_DATA.iterdir() for q in top.rglob("*.nii*")):
        if not path.is_file() or sniff(path).format != NIFTI_MRS:
            continue
        sections.append(audit(path).to_markdown().replace("# Coverage:", "## "))
    out = DOCS / "nifti_mrs.md"
    out.write_text(
        "# NIfTI-MRS coverage (public test files)\n\nGenerated by scripts/build_coverage.py.\n\n"
        + "\n".join(sections)
    )
    print(f"{len(sections)} files -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
