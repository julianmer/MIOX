from __future__ import annotations

import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# own
from miox.audit import Auditor, Coverage, Status  # noqa: E402
from tests.conftest import PUBLIC_DATA  # noqa: E402
from tests.golden.records import ReadRecords  # noqa: E402


#**************************************************************************************************#
#                                         CoverageBuilder                                          #
#**************************************************************************************************#
#                                                                                                  #
# Audits every public file that has a reader and writes one page per format: a summary per file,   #
# the fields keys are read from, and the unused fields grouped by the first part of their path     #
# (list indices and Siemens ``[n]`` indices folded to ``*``).                                      #
#                                                                                                  #
#**************************************************************************************************#
class CoverageBuilder:
    DOCS = Path(__file__).resolve().parents[1] / "docs" / "coverage"
    INDEX = re.compile(r"(?<=/)\d+(?=/|$)|(?<=\[)\d+(?=\])")  # list index, Siemens [n] index

    def __init__(self):
        self.auditor = Auditor()

    def run(self) -> int:
        self.DOCS.mkdir(parents=True, exist_ok=True)
        pages = defaultdict(list)
        for path in ReadRecords().targets():
            try:
                coverage = self.auditor.audit(path)
            except Exception:
                continue  # files that cannot be read are listed in the golden read records
            pages[coverage.format].append(coverage)
        for fmt, coverages in sorted(pages.items()):
            out = self.DOCS / f"{fmt}.md"
            out.write_text(self.page(str(fmt), coverages))
            print(f"{len(coverages)} files -> {out}")
        return 0

    def page(self, fmt: str, coverages: list[Coverage]) -> str:
        lines = [
            f"# Coverage: {fmt}",
            "",
            f"Generated by scripts/build_coverage.py from {len(coverages)} public test files. A "
            "header field is *standard* when a key of the key table is read from it, *other* "
            "when another key is, *unused* when no key is (spec2nii may still use it for the "
            "data, dimensions or geometry).",
            "",
            "## Files",
            "",
            "| file | fields | standard | other | unused |",
            "|---|---|---|---|---|",
        ]
        for c in coverages:
            s = c.summary()
            name = c.path.relative_to(PUBLIC_DATA).as_posix()
            lines.append(
                f"| `{name}` | {len(c.fields)} | {s[Status.STANDARD]} | {s[Status.OTHER]} "
                f"| {s[Status.UNUSED]} |"
            )
        read = Counter((f.path, f.key, f.status) for c in coverages for f in c.fields if f.key)
        lines += ["", "## Fields read into keys", "", "| field | key | status | files |"]
        lines.append("|---|---|---|---|")
        for (path, key, status), n in sorted(read.items()):
            lines.append(f"| `{path}` | {key} | {status} | {n} |")
        unused = defaultdict(set)
        for c in coverages:
            for f in c.fields:
                if f.status == Status.UNUSED:
                    path = self.INDEX.sub("*", f.path)
                    unused[path.split("/")[0]].add(path)
        lines += ["", "## Unused fields", ""]
        for group, paths in sorted(unused.items()):
            lines += [
                f"<details><summary>{group}: {len(paths)} fields</summary>",
                "",
                ", ".join(f"`{p}`" for p in sorted(paths)),
                "",
                "</details>",
                "",
            ]
        return "\n".join(lines)


if __name__ == "__main__":
    sys.exit(CoverageBuilder().run())
