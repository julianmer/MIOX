from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

# own
from miox.audit import Auditor  # noqa: E402
from miox.sniff import Format  # noqa: E402
from tests.conftest import PUBLIC_DATA  # noqa: E402


#**************************************************************************************************#
#                                         CoverageBuilder                                          #
#**************************************************************************************************#
#                                                                                                  #
# Audits every public NIfTI-MRS file and writes the tables into one Markdown page.                 #
#                                                                                                  #
#**************************************************************************************************#
class CoverageBuilder:
    DOCS = Path(__file__).resolve().parents[1] / "docs" / "coverage"

    def __init__(self):
        self.auditor = Auditor()

    def run(self) -> int:
        self.DOCS.mkdir(parents=True, exist_ok=True)
        sections = []
        for path in sorted(q for top in PUBLIC_DATA.iterdir() for q in top.rglob("*.nii*")):
            if not path.is_file() or self.auditor.sniffer.sniff(path).format != Format.NIFTI_MRS:
                continue
            sections.append(self.auditor.audit(path).to_markdown().replace("# Coverage:", "## "))
        out = self.DOCS / "nifti_mrs.md"
        out.write_text(
            "# NIfTI-MRS coverage (public test files)\n\n"
            "Generated by scripts/build_coverage.py.\n\n" + "\n".join(sections)
        )
        print(f"{len(sections)} files -> {out}")
        return 0


if __name__ == "__main__":
    sys.exit(CoverageBuilder().run())
